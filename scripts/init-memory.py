#!/usr/bin/env python3
"""Initialize pi-memory without installing the Pi package or changing Pi settings."""
import argparse
from pathlib import Path
import subprocess
import sys

from memoryio import ROOT, write_text, writer_lock
from memwrite import NOTE_FILES


INDEX = """<!-- Auto-generated by pi-memory/scripts/memindex.py — do not edit manually -->
# Reports INDEX

(Will be auto-generated on first memindex.py run)
"""


def initialize(root, name, email):
    root.mkdir(parents=True, exist_ok=True)
    with writer_lock(root):
        meta = root / '_meta'
        meta.mkdir(exist_ok=True)

        def git(*args):
            return subprocess.run(['git', '-C', str(root), *args], check=True)

        if not (root / '.git').exists():
            git('init')
            for key in ('core.quotepath', 'core.fileMode', 'core.autocrlf'):
                git('config', key, 'false')
        for key, value, fallback in [('user.name', name, 'pi-memory'),
                                     ('user.email', email, 'agent@localhost')]:
            if value is not None:
                git('config', key, value)
                continue
            configured = subprocess.run(
                ['git', '-C', str(root), 'config', '--get', key], capture_output=True,
            )
            if configured.returncode == 1:
                git('config', key, fallback)
            elif configured.returncode != 0:
                raise subprocess.CalledProcessError(configured.returncode, configured.args)

        files = {f'_meta/{NOTE_FILES[k][0]}': NOTE_FILES[k][1] for k in ('global', 'preference')}
        files['INDEX.md'] = INDEX
        created = []
        for filename, content in files.items():
            path = root / filename
            if not path.exists():
                write_text(path, content)
                created.append(filename)
        if created:
            git('add', '--', *created)
            git('commit', '--only', '-m', 'Initialize pi-memory structure', '--', *created)
        print(f'Memory ready: {root}')
        print('The Pi package is not installed by this script.')
    return 0


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', default=ROOT, help='Reports root (default: MEMQ_ROOT or ~/reports)')
    parser.add_argument('--name', help='Git author name (keep existing; fallback: pi-memory)')
    parser.add_argument('--email', help='Git author email (keep existing; fallback: agent@localhost)')
    args = parser.parse_args(argv)
    return initialize(Path(args.root).expanduser().resolve(), args.name, args.email)


if __name__ == '__main__':
    try:
        sys.exit(main(sys.argv[1:]))
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        sys.exit(1)
